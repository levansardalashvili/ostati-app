- **კომუნიკაცია:** ჩატის შეტყობინებები, ფოტოები და ფასის შეთავაზებები.
- **შეფასებები:** ვარსკვლავები, ტექსტი და ფოტოები, რომლებსაც სამუშაოს დასრულების შემდეგ ტოვებთ (ოსტატის პასუხიც).
- **რეპორტები და დაბლოკვა:** თუ ვინმეს ან რამეს დაარეპორტებთ, ვინახავთ რეპორტს, მიზეზს და თქვენ მიერ დამატებულ დეტალებს; ასევე ვინახავთ, ვინ დაბლოკეთ.

### ავტომატურად შექმნილი მონაცემები

- მოწყობილობის **push-იდენტიფიკატორი** (token) და პლატფორმა (Android/iOS) — შეტყობინებების გასაგზავნად. სისტემიდან გასვლისას ის გამოირთვება.
- თქვენი შეტყობინებების პარამეტრები.
- სამუშაოს სტატუსები, ოსტატის ხელმისაწვდომობა, რეიტინგი და დასრულებული სამუშაოების რაოდენობა.

### მესამე მხარეებიდან მიღებული მონაცემები

Google-ით ან Apple-ით შესვლისას ვიღებთ იმ მონაცემებს, რომლებსაც ეს სერვისები გვაწვდიან (სახელი, ელფოსტა).

**რასაც არ ვაგროვებთ:** ზუსტ GPS-ადგილმდებარეობას (მისამართს თავად წერთ), კონტაქტების სიას, სარეკლამო იდენტიფიკატორებს.

