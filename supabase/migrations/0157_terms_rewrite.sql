## 1. რა არის Ostato

Ostato („ჩვენ“) არის მობილური აპლიკაცია და ვებგვერდი, რომელიც საქართველოში აკავშირებს სახლის სამუშაოს შემკვეთს („**დამკვეთი**“, აპში — „მომხმარებელი“) ადგილობრივ ოსტატთან („**ოსტატი**“).

Ostato **არ არის** სამუშაოს შემსრულებელი, არ არის დამკვეთის ან ოსტატის დამსაქმებელი ან წარმომადგენელი და არ არის მათ შორის შეთანხმების მხარე. სამუშაოს პირობებზე, ფასზე, ხარისხსა და შესრულებაზე პასუხს აგებენ დამკვეთი და ოსტატი.

ამ პირობებთან ერთად მოქმედებს [კონფიდენციალურობის პოლიტიკა](/privacy) და [საზოგადოების წესები](/community-guidelines). აპის ან ვებგვერდის გამოყენებით მათ ეთანხმებით. თუ არ ეთანხმებით, ნუ გამოიყენებთ.

## 2. ვის შეუძლია გამოყენება

- Ostato-ის გამოყენება შეუძლია **18 წლის და უფროს** პირს.
- ოსტატი მოქმედებს კანონის შესაბამისად. თუ სამუშაოს შესასრულებლად ლიცენზია ან ნებართვაა საჭირო, ის ოსტატს უნდა ჰქონდეს.
- Ostato განკუთვნილია საქართველოში შესასრულებელი სამუშაოებისთვის.

## 3. ანგარიში

- **ერთ ანგარიშს ერთი როლი აქვს**: ის ან დამკვეთისაა, ან ოსტატის. როლის შეცვლა შეუძლებელია.
- დარეგისტრირება შეგიძლიათ ელფოსტით, Google-ით ან Apple-ით. მიუთითეთ სწორი მონაცემები და განაახლეთ, თუ შეიცვლება.
- ერთ ადამიანს ერთი ანგარიში აქვს. სხვისი სახელით ან ყალბი მონაცემებით რეგისტრაცია აკრძალულია.
- შესვლის მონაცემებს თავად იცავთ. თქვენი ანგარიშიდან შესრულებულ მოქმედებებზე პასუხს თქვენ აგებთ. თუ ანგარიშზე სხვამ მოიპოვა წვდომა, დაუყოვნებლივ შეგვატყობინეთ.

## 4. ოსტატის ვერიფიკაცია

ოსტატი ვერიფიკაციას აპიდან ითხოვს: იღებს სელფის, ჩვენი გუნდი კი ადარებს მას პროფილის ფოტოს და ამოწმებს, ერთი და იგივე ადამიანია თუ არა.

- ვერიფიკაციის გარეშე ოსტატი **ფასს ვერ შესთავაზებს**.
- „ვერიფიცირებული“ ნიშანი **მხოლოდ იმას ადასტურებს, რომ პროფილი ნამდვილ ადამიანს ეკუთვნის**. ის არ ადასტურებს სამუშაოს ხარისხს, კვალიფიკაციას, ლიცენზიას ან ნასამართლეობის არქონას.
- თუ ვერიფიცირებული ოსტატი შეცვლის პროფილის ფოტოს, სახელს ან გვარს, ვერიფიკაცია ხელახლა მოწმდება. მანამდე ფასის შეთავაზება შეუძლებელია.
- სელფი კერძოა და არსად ქვეყნდება ([კონფიდენციალურობის პოლიტიკა](/privacy)).
- ვერიფიკაციაზე შეგვიძლია უარი ვთქვათ ან მოვხსნათ, თუ მონაცემები არასწორია ან წესები დაირღვა. მოხსნისას ოსტატის ფასის შეთავაზებები მომლოდინე განცხადებებზე უქმდება.

## 5. განცხადება, შეთავაზება და არჩევა

- **განცხადება.** დამკვეთი უთითებს კატეგორიას, აღწერას, რაიონს, მისამართს, სასურველ თარიღსა და დროს და, სურვილისამებრ, ფოტოებს. **დამკვეთი ფასს არ უთითებს.** ერთდროულად შეიძლება იყოს 10-მდე ღია განცხადება.
- **მისამართი.** ზუსტ მისამართს ხედავს მხოლოდ არჩეული ოსტატი. დანარჩენ ოსტატებს მხოლოდ რაიონი უჩანთ.
- **პირადი მოთხოვნა.** თუ დამკვეთი ოსტატს პირდაპირ მისწერს, იქმნება მოთხოვნა, რომელსაც მხოლოდ ეს ოსტატი ხედავს. ოსტატს შეუძლია უარი თქვას, დამკვეთს კი — მოთხოვნა ყველა ოსტატისთვის გახსნას.
- **შეთავაზება.** ვერიფიცირებული ოსტატი განცხადების ნახვის შემდეგ სთავაზობს **კონკრეტულ ფასს**. სანამ დამკვეთი არჩევანს გააკეთებს, ოსტატს შეუძლია შეთავაზების გაუქმება.
- **ჩატი.** დეტალებს მხარეები ჩატში აზუსტებენ. ოსტატს შეუძლია ჩატში ახალი ფასი შესთავაზოს, დამკვეთი კი ეთანხმება ან უარყოფს. ჩატის შეთავაზება 7 დღე მოქმედებს.
- **არჩევა.** დამკვეთი ირჩევს ოსტატს, შეთანხმებული ფასი ფიქსირდება და ოსტატს ეცნობება. დანარჩენ დაინტერესებულ ოსტატებს ეცნობებათ, რომ სამუშაო სხვას გადაეცა.

## 6. ფასი და ანგარიშსწორება

- ფასს ოსტატი სთავაზობს, დამკვეთი კი ირჩევს. აპში დაფიქსირებული ფასი მხარეთა შეთანხმების ჩანაწერია.
- **Ostato-ში გადახდა არ ხდება.** აპი არ იღებს, არ ინახავს და არ გადასცემს თანხას. ანგარიშსწორება ხდება დამკვეთსა და ოსტატს შორის, აპის გარეთ, მათივე შეთანხმებით.
- Ostato არ იღებს საკომისიოს და არ არის პასუხისმგებელი გადახდაზე, თანხის დაბრუნებაზე ან ფასთან დაკავშირებულ დავაზე მხარეებს შორის.

## 7. შესრულება, დასრულება და შეფასება

- ოსტატი სამუშაოს შეთანხმებულ დროს ასრულებს და აპში მონიშნავს „სამუშაო დავასრულე“. დაგეგმილ დრომდე ამის მონიშვნა შეუძლებელია. თუ ოსტატმა არ მონიშნა, დაგეგმილი დროის შემდეგ ამის გაკეთება დამკვეთსაც შეუძლია.
- დამკვეთი ადასტურებს დასრულებას ან აღნიშნავს პრობლემას (იხ. [8. თავი](#s8)).
- თუ დამკვეთი 72 საათის განმავლობაში არ გამოეხმაურება, დასრულება ავტომატურად დადასტურდება.
- დასრულების შემდეგ დამკვეთი **ვალდებულია შეაფასოს ოსტატი**. სანამ შეფასებას არ დატოვებს, აპი შეფასების გვერდს გაუხსნის.
- დაგეგმილი დროის შეცვლა შეუძლია დამკვეთს; ოსტატს ეს ეცნობება.
- ორივე მხარე მოქმედებს კეთილსინდისიერად, პატივისცემით და კანონის დაცვით.

## 8. დავები და რეპორტები

- თუ სამუშაო არ შესრულებულა ან ცუდად შესრულდა, დამკვეთს შეუძლია დასრულების დადასტურების ნაცვლად აღნიშნოს **პრობლემა** და მიუთითოს მიზეზი. ერთ განცხადებაზე ეს მაქსიმუმ ორჯერ შეიძლება.
- დავის დროს ოსტატს შეუძლია დაწეროს თავისი მხარე.
- დავას ჩვენი გუნდი განიხილავს. ამისთვის შეიძლება გამოვიყენოთ განცხადება, ჩატი და ფოტოები. შედეგად სამუშაო ან ხელახლა დასადასტურებლად უბრუნდება დამკვეთს, ან უქმდება.
- ჩვენი გადაწყვეტილება ეხება მხოლოდ სამუშაოს სტატუსს აპში. ის არ წყვეტს ფულად ან სხვა მოთხოვნებს მხარეებს შორის.
- გარდა ამისა, შეგიძლიათ დაარეპორტოთ სამუშაო ან მომხმარებელი, მაგალითად, თუ მხარე არ გამოცხადდა ან უხეშად მოიქცა.

## 9. გაუქმება და ვადები

- **დამკვეთს** განცხადების გაუქმება შეუძლია, სანამ ოსტატს აირჩევს. ოსტატის არჩევის შემდეგ — მიზეზის მითითებით.
- **ოსტატს** არჩეული სამუშაოს გაუქმება შეუძლია მიზეზის მითითებით. ამ შემთხვევაში დამკვეთს შეუძლია განცხადება დანარჩენი ოსტატებისთვის ხელახლა გახსნას, გაუქმების ავტორი ოსტატი კი მას აღარ დაინახავს.
- ოსტატის აურჩეველი განცხადება 30 დღის შემდეგ ავტომატურად უქმდება. ვადის ამოწურვამდე შეგახსენებთ და შეგიძლიათ განცხადება განაახლოთ.
- ხშირი უსაფუძვლო გაუქმება ან გამოუცხადებლობა შეიძლება გახდეს ანგარიშის შეზღუდვის მიზეზი.

## 10. შეფასებები და თქვენი კონტენტი

- შეფასებას ტოვებს მხოლოდ დამკვეთი, დასრულებულ სამუშაოზე. შეფასება **ანონიმურია**: ავტორი არ ჩანს არც საჯაროდ და არც ოსტატისთვის. ოსტატს შეუძლია შეფასებას ერთხელ უპასუხოს.
- შეფასებას ან პასუხს დავმალავთ, თუ ის შეურაცხმყოფელი, ყალბი ან სამუშაოსთან შეუსაბამოა, ან სხვის პირად მონაცემებს შეიცავს.
- თქვენ მიერ ატვირთული კონტენტი (ტექსტი, ფოტოები, პროფილი, შეფასებები) თქვენია. მისი ატვირთვით გვაძლევთ უფლებას, გამოვიყენოთ ის მხოლოდ Ostato-ის მუშაობისთვის: მაგალითად, ვაჩვენოთ მეორე მხარეს, შევინახოთ შეთანხმების ჩანაწერად და გამოვიყენოთ უსაფრთხოების მიზნით.
- ატვირთეთ მხოლოდ ის, რისი ატვირთვის უფლებაც გაქვთ და რაც არ არღვევს სხვის უფლებებს ან კანონს.

## 11. აკრძალული ქცევა

აკრძალულია:

- ყალბი ან შეცდომაში შემყვანი პროფილის ან განცხადების შექმნა, ან სხვის სახელით მოქმედება;
- შეურაცხყოფა, მუქარა, შევიწროება ან დისკრიმინაცია;
- უკანონო სამუშაოს მოთხოვნა ან შეთავაზება, უკანონო კონტენტის განთავსება;
- სხვისი მონაცემების ნებართვის გარეშე შეგროვება ან გამოყენება;
- ყალბი შეფასება ან შეფასებებით მანიპულირება;
- Ostato-ის მუშაობის შეფერხება, დაცვის მექანიზმების გვერდის ავლა, ავტომატური მასობრივი წვდომა.

დეტალები — [საზოგადოების წესებში](/community-guidelines).

## 12. ანგარიშის შეზღუდვა, შეჩერება და დაბლოკვა

- თუ წესები დაირღვა, მივიღეთ რეპორტი, არსებობს უსაფრთხოების საფრთხე ან ამას კანონი მოითხოვს, შეგვიძლია: შევაჩეროთ ანგარიში, მოვხსნათ ან დავმალოთ კონტენტი და შეფასება, მოვხსნათ ვერიფიკაცია ან გავაუქმოთ განცხადება. ზომა დარღვევის სიმძიმეზეა დამოკიდებული.
- შეჩერებულ ანგარიშზე შესვლა და ჩატში წერა შეუძლებელია. შეჩერების მიზეზს გაცნობებთ.
- თუ გადაწყვეტილება არასწორად მიგაჩნიათ, მოგვწერეთ [დახმარების გვერდიდან](/support) — განვიხილავთ.
- ნებისმიერ მომხმარებელს შეუძლია სხვა მომხმარებლის დაბლოკვა და ჩატიდან დარეპორტება.

## 13. ანგარიშის წაშლა

- ანგარიშის წაშლა ნებისმიერ დროს შეგიძლიათ აპიდან: **პროფილი → ანგარიშის პარამეტრები → ანგარიშის წაშლა** ([ინსტრუქცია](/delete-account)). წაშლა შეუძლებელია, სანამ მიმდინარე სამუშაო არ დასრულდება ან არ გაუქმდება.
- წაშლისას თქვენი მონაცემები იშლება. დასრულებული სამუშაოები და მათი შეფასებები რჩება ანონიმურად, თქვენი სახელის, მისამართისა და ფოტოების გარეშე ([კონფიდენციალურობის პოლიტიკა](/privacy)).
- ჩვენც შეგვიძლია ანგარიშის გაუქმება ამ პირობების სერიოზული დარღვევისას ან კანონის მოთხოვნით.

## 14. Ostato-ის პასუხისმგებლობის ფარგლები

- Ostato ოსტატის კვალიფიკაციას, სამუშაოს ხარისხს და მის შედეგს არ ამოწმებს და მათზე პასუხს არ აგებს. ვერიფიკაცია მხოლოდ ვინაობას ადასტურებს (იხ. [4. თავი](#s4)).
- სამუშაოს შესრულებასთან, ანგარიშსწორებასთან ან სამუშაოს დროს მიყენებულ ზიანთან დაკავშირებული პრეტენზია მხარეებმა ერთმანეთს უნდა წაუყენონ.
- ვცდილობთ, Ostato შეუფერხებლად მუშაობდეს, თუმცა ვერ გარანტირებთ, რომ ის ყოველთვის შეცდომებისა და შეფერხებების გარეშე იმუშავებს.
- ეს თავი არ ზღუდავს თქვენს უფლებებს, რომელთა შეზღუდვაც კანონით დაუშვებელია.

## 15. ინტელექტუალური საკუთრება

Ostato-ის სახელი, ლოგო, დიზაინი, აპლიკაცია და ტექსტები ჩვენ გვეკუთვნის. გაძლევთ უფლებას, გამოიყენოთ Ostato ამ პირობების ფარგლებში. აკრძალულია აპლიკაციის კოპირება, დეკომპილაცია, მონაცემების მასობრივი ამოღება და ჩვენი სახელის ან ლოგოს ნებართვის გარეშე გამოყენება.

## 16. სხვა სერვისები და აპლიკაციების მაღაზიები

- Ostato იყენებს სხვა კომპანიების სერვისებს: შესვლისთვის (Google, Apple), შეტყობინებებისთვის და მისამართის ძებნისთვის ([კონფიდენციალურობის პოლიტიკა](/privacy)). მათზე მათი პირობები ვრცელდება.
- თუ აპლიკაციას App Store-იდან ან Google Play-დან იყენებთ, ეს პირობები მოქმედებს ჩვენსა და თქვენს შორის. Apple და Google ამ პირობების მხარე არ არიან და აპლიკაციის მხარდაჭერაზე პასუხს არ აგებენ.

## 17. ცვლილებები და შეტყობინებები

- პირობები შეიძლება შევცვალოთ. მნიშვნელოვანი ცვლილების შესახებ გაცნობებთ აპში ან ვებგვერდზე. ბოლო განახლების თარიღი ტექსტის თავშია. ცვლილების შემდეგ Ostato-ის გამოყენება ახალ პირობებზე თანხმობას ნიშნავს. თუ არ ეთანხმებით, შეგიძლიათ ანგარიში წაშალოთ.
- შეტყობინებებს გიგზავნით აპში, push-შეტყობინებით ან ელფოსტით. push-შეტყობინებების გამორთვა აპის პარამეტრებში შეგიძლიათ, თუმცა უსაფრთხოებისა და ანგარიშის შესახებ მნიშვნელოვანი შეტყობინება მაინც შეიძლება გამოგიგზავნოთ.
- თუ ამ პირობების რომელიმე პუნქტი ბათილად ჩაითვლება, დანარჩენი პუნქტები ძალაში რჩება.

