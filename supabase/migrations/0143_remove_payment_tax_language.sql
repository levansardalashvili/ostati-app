## 3. მომხმარებლებისთვის

- აღწერეთ სამუშაო სწორად და სრულად; ატვირთეთ მხოლოდ ის ფოტოები, რომლებიც სამუშაოს ეხება (ადამიანების პირადი ფოტოების გარეშე).
- განათავსეთ მხოლოდ **რეალური** განცხადება; არ გამოიყენოთ პლატფორმა ფასების „გასაგებად“ ან ოსტატების დროის დასაკარგად.
- არ მოითხოვოთ სამუშაო, რომელიც უკანონოა ან რომლის უსაფრთხოდ შესრულება შეუძლებელია.
- ოსტატს მიეცით სამუშაოსთვის საჭირო წვდომა და პირობები; დაუშვით მისი დროული ჩამოსვლა/შესრულება.
- სამუშაოს დასრულების შემდეგ **დაადასტურეთ და შეაფასეთ** პატიოსნად. თუ პრობლემაა, გამოიყენეთ „პრობლემა მაქვს“ და არა შეფასებით მანიპულირება.
- არ დაემუქროთ ოსტატს ცუდი შეფასებით იმისთვის, რომ ფასი დაგიკლოთ ან სამუშაო დამატებით უფასოდ შეასრულოს.

## 4. ოსტატებისთვის

- პროფილში მიუთითეთ **მხოლოდ ის სპეციალობა და გამოცდილება, რაც გაქვთ**; ნამუშევრებისა და სერთიფიკატების ფოტოები უნდა იყოს თქვენი.
- შესთავაზეთ **რეალური ფასი**; დარწმუნდით, რომ სამუშაოს შეასრულებთ. ფასს ნუ შეცვლით შეთანხმების შემდეგ დამატებითი ხარჯის დასაბუთებული მიზეზის გარეშე.
- გამოცხადდით შეთანხმებულ დროს; თუ ვერ ახერხებთ, დროულად გააუქმეთ განცხადება მიზეზის მითითებით — გამოუცხადებლობა ზიანს აყენებს მომხმარებელს და თქვენს რეპუტაციას.
- ისარგებლეთ ზუსტი მისამართით **მხოლოდ სამუშაოს შესასრულებლად**; არ გაავრცელოთ და არ გამოიყენოთ სხვა მიზნით.
- აწარმოეთ საქმიანობა კანონის შესაბამისად (ლიცენზია, უსაფრთხოების ნორმები), იზრუნეთ საკუთარ ინსტრუმენტებზე და დაზღვევაზე, სადაც საჭიროა.
- ვერიფიკაციის სელფი უნდა იყოს **თქვენი**; სხვისი ფოტოს გამოყენება აკრძალულია და იწვევს ვერიფიკაციის მოხსნას/ანგარიშის შეჩერებას.

## 5. შეფასებები

- შეფასება უნდა ასახავდეს რეალურ გამოცდილებას; აკრძალულია ყალბი ან ფასიანი შეფასებები, შეფასების გაცვლა/შეთანხმება, კონკურენტის დაკნინება.
- შეფასება ანონიმურია — ავტორის „გამოცნობა“ და მასზე ზეწოლა დაუშვებელია.
- ოსტატს შეუძლია შეფასებას ერთხელ **თავაზიანად** უპასუხოს. პასუხში ავტორის პირადი ინფორმაციის გამჟღავნება აკრძალულია.
- შეურაცხმყოფელ, ყალბ ან შეუსაბამო შეფასებებს/პასუხებს ვმალავთ.

## 6. ჩატი და კომუნიკაცია

- იყავით თავაზიანი და კონკრეტული; დეტალები (ფასი, დრო, სამუშაოს მოცულობა) შეათანხმეთ **ჩატში**, რათა დავის შემთხვევაში ჩანაწერი გქონდეთ.
- არ გაუზიაროთ მეორე მხარეს პაროლები, კოდები ან სხვა საიდუმლო ინფორმაცია.
- არ გამოიყენოთ ჩატი შეურაცხყოფისთვის, მუქარისთვის ან არასასურველი შეტყობინებებისთვის. არასასურველ მომხმარებელს შეგიძლიათ **დაბლოკოთ**.
- ჩატიდან შეგიძლიათ მომხმარებელი **დაარეპორტოთ**.

## 7. დარღვევის შემჩნევისას

- დააფიქსირეთ პრობლემა განცხადებიდან („პრობლემის შეტყობინება“) ან ჩატიდან („დარეპორტება“).
- გადაუდებელი საფრთხის შემთხვევაში პირველ რიგში დაუკავშირდით შესაბამის სამსახურს (პოლიცია, სასწრაფო დახმარება).
- რეპორტებს ჩვენი გუნდი განიხილავს. რეპორტიორის ვინაობა დარეპორტებულ პირს არ ეჩვენება.

## 8. დარღვევის შედეგები

დარღვევის სიმძიმისა და გამეორების მიხედვით შეიძლება მოხდეს:

- კონტენტის ან შეფასების მოხსნა/დამალვა;
- განცხადების გაუქმება;
- **ვერიფიკაციის მოხსნა**;
- **ანგარიშის შეჩერება** (შესვლა და შეტყობინებების გაგზავნა შეუძლებელი ხდება);
- სერიოზულ შემთხვევაში — სამუდამო შეზღუდვა და, საჭიროებისას, უფლებამოსილი ორგანოებისთვის მიმართვა.

