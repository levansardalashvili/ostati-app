- **შეტყობინებები** — push-შეტყობინებების მისაღებად.

ნებართვის უარყოფის შემთხვევაში აპი კვლავ იმუშავებს, უბრალოდ შესაბამისი ფუნქცია მიუწვდომელი იქნება. ნებართვის შეცვლა შეგიძლიათ მოწყობილობის პარამეტრებში.

## 6. ვისთან ვიზიარებთ მონაცემებს

- **მეორე მხარესთან** — იმ ოდენობით, რაც სამუშაოსთვის სჭირდება (იხ. [3. თავი](#s3)).
- **მომსახურების მიმწოდებლებთან**, რომლებიც ჩვენი სახელით ამუშავებენ მონაცემებს:
  - **Supabase** — მონაცემთა ბაზა, ავტორიზაცია, ფაილების საცავი;
  - **Expo** — push-შეტყობინებების გადაცემა;
  - **Google და Apple** — შესვლა ამ ანგარიშებით;
  - **OpenStreetMap Nominatim** — მისამართის ძებნა (იქ იგზავნება მხოლოდ თქვენ მიერ აკრეფილი მისამართის ტექსტი);
  - **Vercel** — ვებგვერდის ჰოსტინგი.
- **უფლებამოსილ ორგანოებთან**, თუ ამას კანონი მოითხოვს.

მონაცემებს **არ ვყიდით** და სარეკლამო მიზნით მესამე მხარეებს არ ვუზიარებთ. ზოგიერთი მომსახურების მიმწოდებელი მონაცემებს საქართველოს გარეთ ამუშავებს; ასეთ შემთხვევაში ვეყრდნობით მათ ხელშეკრულებით ნაკისრ დაცვის ვალდებულებებს.

## 7. ვებგვერდი და ქუქიები

საჯარო ვებგვერდი **არ იყენებს** სააღრიცხვო, სარეკლამო ან თვალთვალის ქუქიებს და არ მოითხოვს რეგისტრაციას. ჰოსტინგის სერვისი (Vercel) ინახავს სტანდარტულ ტექნიკურ ჟურნალებს (მაგ. IP-მისამართი, ვიზიტის დრო, გვერდი) უსაფრთხოებისა და გამართული მუშაობისთვის. ჩვენთან დაკავშირებისას მოწოდებულ ინფორმაციას ვინახავთ თქვენი მოთხოვნის დასამუშავებლად.

ადმინისტრაციული პანელი განკუთვნილია მხოლოდ Ostato-ის გუნდისთვის და სესიისთვის ტექნიკურ ქუქის იყენებს.

## 8. რამდენ ხანს ვინახავთ

- მონაცემებს ვინახავთ, სანამ თქვენი ანგარიში არსებობს.
- **ანგარიშის წაშლისას** იშლება თქვენი პროფილი, ფოტოები, ჩატები, სელფი და აქტიური განცხადებები.
- **დასრულებული სამუშაოები და მათზე დაწერილი შეფასებები** ანონიმიზებული სახით რჩება, რათა ოსტატის რეიტინგი და ისტორია არ დაზიანდეს — მათში თქვენი სახელი, მისამართი და ფოტოები აღარ არის.
- **რეპორტებს** ვინახავთ უსაფრთხოების მიზნით.
