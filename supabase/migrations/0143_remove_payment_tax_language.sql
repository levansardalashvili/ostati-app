## 1. პლატფორმა

Ostato („ჩვენ“, „პლატფორმა“) არის ორმხრივი პლატფორმა (მობილური აპლიკაცია და ვებგვერდი), რომელიც საქართველოში აკავშირებს სახლის სერვისების მაძიებელ მომხმარებლებს („**დამკვეთი**“) ადგილობრივ ოსტატებთან („**ოსტატი**“). ჩვენ ვქმნით ადგილს ერთმანეთის პოვნის, ურთიერთობისა და შეთანხმებისთვის.

**Ostato არ არის** სამუშაოს შემსრულებელი, დამკვეთისა და ოსტატის დამქირავებელი ან წარმომადგენელი და არც მათ შორის შეთანხმების მხარე. სამუშაოს პირობებზე, ფასზე, ხარისხზე და შესრულებაზე პასუხისმგებელნი არიან თავად დამკვეთი და ოსტატი.

ამ პირობებთან ერთად თქვენზე ვრცელდება [კონფიდენციალურობის პოლიტიკა](/privacy) და [საზოგადოების წესები](/community-guidelines). პლატფორმის გამოყენებით ეთანხმებით მათ ერთობლიობას. თუ არ ეთანხმებით, პლატფორმას ნუ გამოიყენებთ.

## 2. ვის შეუძლია გამოყენება

- პლატფორმის გამოყენება შეუძლია მხოლოდ **18 წლის და უფროსი** პირს, რომელსაც კანონით აქვს ხელშეკრულების დადების უფლება.
- ოსტატმა უნდა იმოქმედოს კანონმდებლობის შესაბამისად და, საჭიროების შემთხვევაში, ჰქონდეს სამუშაოსთვის საჭირო ლიცენზია/ნებართვა.
- პლატფორმა განკუთვნილია საქართველოში მიწოდებული სერვისებისთვის.

## 3. ანგარიში

- **ერთი ანგარიში — ერთი როლი.** ანგარიში არის ან დამკვეთის, ან ოსტატის.
- შეგიძლიათ დარეგისტრირდეთ ელფოსტით, Google-ით ან Apple-ით. მიუთითეთ **ზუსტი და მიმდინარე** ინფორმაცია და განაახლეთ ის ცვლილებისას.
- დაიცავით თქვენი შესვლის მონაცემები. ანგარიშზე შესრულებულ მოქმედებებზე თქვენ ხართ პასუხისმგებელი; უნებართვო წვდომის შემთხვევაში დაუყოვნებლივ შეგვატყობინეთ.
- ერთ პირს ერთი ანგარიში აქვს; სხვისი სახელით ან ყალბი მონაცემებით ანგარიშის შექმნა აკრძალულია.

## 4. ოსტატების ვერიფიკაცია

ოსტატს შეუძლია ვერიფიკაცია მოითხოვოს: აპში აკეთებს სელფის, ჩვენი გუნდი ადარებს მას პროფილის ფოტოს და, ფოტოები ერთი ადამიანისაა თუ არა, იღებს გადაწყვეტილებას.

- ვერიფიკაციის გარეშე ოსტატი **ფასს ვერ სთავაზობს** განცხადებას.
- „ვერიფიცირებული“ ნიშანი **მხოლოდ ვინაობის დადასტურებას** ნიშნავს. ის **არ არის** გარანტია სამუშაოს ხარისხზე, კვალიფიკაციაზე, ლიცენზიაზე ან ნასამართლეობის არარსებობაზე.
- სელფი კერძოა და არ ქვეყნდება (დეტალები — [კონფიდენციალურობის პოლიტიკაში](/privacy)).
- შეგვიძლია ვერიფიკაციაზე უარი ვთქვათ ან უკვე მინიჭებული მოვხსნათ, თუ წესები დაირღვა ან მონაცემები არასწორია.

## 5. განცხადებები და შეთავაზებები

- **განცხადება.** დამკვეთი აქვეყნებს განცხადებას (კატეგორია, აღწერა, ფოტოები, რაიონი, მისამართი, სასურველი დრო). **დამკვეთი ფასს არ უთითებს.** განცხადებების რაოდენობა და მათი მოქმედების ვადა შეზღუდულია (მიმდინარე მნიშვნელობები აპშია მითითებული და შეიძლება შეიცვალოს).
- **მისამართი.** ზუსტი მისამართი სხვა ოსტატებს არ ჩანს; ის ხელმისაწვდომია მხოლოდ არჩეული ოსტატისთვის.
- **შეთავაზება.** ვერიფიცირებული ოსტატი განცხადების დეტალების ნახვის შემდეგ სთავაზობს **კონკრეტულ ფასს**. ოსტატს შეუძლია დაინტერესება გააუქმოს, სანამ დამკვეთმა არჩევანი არ გააკეთა.
- **ჩატი.** მხარეები დეტალებს ჩატში აზუსტებენ. ფასის შეცვლა ხდება სტრუქტურირებული ბარათით: ოსტატი სთავაზობს, დამკვეთი ეთანხმება ან უარყოფს. შეთავაზებას ვადა აქვს.
- **არჩევა.** დამკვეთი ირჩევს ოსტატს; შეთანხმებული ფასი ფიქსირდება და არჩეულ ოსტატს ეცნობება. დანარჩენ დაინტერესებულ ოსტატებს ეცნობებათ, რომ განცხადება სხვას გადაეცა.
- ფასი და პირობები, რომელზეც დამკვეთი და ოსტატი შეთანხმდნენ, არის **მათ შორის** შეთანხმება; Ostato მასში მხარე არ არის.

## 6. სამუშაოს შესრულება, დასრულება და შეფასება

- ოსტატი ასრულებს სამუშაოს შეთანხმებულ დროს და აპში აფიქსირებს დასრულებას („სამუშაო დავასრულე“). დაგეგმილ დრომდე დასრულების მონიშვნა შეუძლებელია.
- დამკვეთს ეგზავნება დასრულების ბარათი. დამკვეთი **ადასტურებს დასრულებას და აფასებს ოსტატს** — შეფასება სავალდებულო ეტაპია.
- თუ დამკვეთი განსაზღვრულ ვადაში (ამჟამად 72 საათი) არ რეაგირებს, დასრულება შეიძლება ავტომატურად დადასტურდეს; შეფასების დატოვება მაინც შესაძლებელია.
- სამუშაოს დროს ორივე მხარე ვალდებულია, იმოქმედოს კეთილსინდისიერად, მშვიდად და კანონის დაცვით.

## 7. დავები

- თუ სამუშაო არ არის შესრულებული ან შესრულებულია არასათანადოდ, დამკვეთს შეუძლია დააფიქსიროს **პრობლემა** დასრულების დადასტურების ნაცვლად. განცხადება „დავაზე“ გადადის და მას ჩვენი გუნდი განიხილავს.
- განხილვისას შეგვიძლია გამოვიყენოთ მხარეთა ჩანაწერები, ჩატი და ფოტოები (იხ. [კონფიდენციალურობა](/privacy)). გადაწყვეტილებით განცხადება შეიძლება გაუქმდეს ან დასადასტურებლად დაუბრუნდეს დამკვეთს.
- ერთ განცხადებაზე დავის დაფიქსირება შეზღუდულია (ამჟამად ორჯერ).
- ჩვენი გადაწყვეტილება არ ზღუდავს მხარეთა უფლებას, ზიანის ანაზღაურება მოითხოვონ კანონით დადგენილი წესით.
- დავის მიღმა, დამატებით შეგიძლიათ მომხმარებელი ან სამუშაო დაარეპორტოთ (მაგ. გამოუცხადებლობა, უხამსი ქცევა).

## 8. გაუქმება და განცხადების ვადა

- **დამკვეთს** შეუძლია განცხადების გაუქმება მოლოდინის ეტაპზე; ოსტატის არჩევის შემდეგ — მიზეზის მითითებით.
- **ოსტატს** შეუძლია არჩეული სამუშაოს გაუქმება მიზეზის მითითებით. ასეთ შემთხვევაში დამკვეთს შეუძლია განცხადება ხელახლა გახსნას დანარჩენი ოსტატებისთვის; გაუქმებული ოსტატი განცხადებას აღარ ხედავს.
- მოლოდინის ეტაპზე მყოფი განცხადება განსაზღვრული ვადის (ამჟამად 30 დღე) გასვლისას ავტომატურად უქმდება; ვადის ამოწურვამდე შეგახსენებთ და შეგიძლიათ განცხადება განაახლოთ.
- სისტემატური, უსაფუძვლო გაუქმებები ან გამოუცხადებლობა შეიძლება გახდეს ანგარიშის შეზღუდვის საფუძველი.

## 9. შეფასებები და თქვენი კონტენტი

- **შეფასებები** ჩანს **ანონიმურად**: ავტორი არც საჯაროდ ჩანს და არც ოსტატისთვის. შეფასების დატოვება შეუძლია მხოლოდ დამკვეთს, სამუშაოს დასრულების შემდეგ; ოსტატს შეუძლია ერთხელ უპასუხოს.
- გვაქვს უფლება, დავმალოთ ან მოვხსნათ შეფასება/პასუხი, რომელიც არღვევს წესებს (შეურაცხმყოფელი, ყალბი, შეუსაბამო, პირად მონაცემებს შეიცავს).
- **თქვენი კონტენტი** (ტექსტი, ფოტოები, პროფილი, შეფასებები) რჩება თქვენი. თქვენ გვანიჭებთ არაექსკლუზიურ, უფლებას, გამოვიყენოთ ის პლატფორმის მუშაობისთვის (მაგ. მეორე მხარისთვის ჩვენება, შეთანხმების დამადასტურებელი ჩანაწერი, უსაფრთხოება).
- გარანტიას იძლევით, რომ გაქვთ კონტენტის ატვირთვის უფლება და ის არ არღვევს სხვისი უფლებებს ან კანონს.
- გამოხმაურება და შეთავაზებები პლატფორმის გაუმჯობესებაზე შეგვიძლია გამოვიყენოთ ანაზღაურების გარეშე.

## 10. აკრძალული ქცევა

არ შეიძლება:

- ყალბი, შეცდომაში შემყვანი ან სხვისი სახელით პროფილის/განცხადების შექმნა;
- სხვა მომხმარებლის შეურაცხყოფა, დამუქრება, შევიწროება ან დისკრიმინაცია;
- უკანონო სამუშაოს ან კონტენტის განთავსება, ან უკანონო სამუშაოს შეთავაზება;
- პლატფორმის გვერდის ავლა თაღლითური მიზნით, სხვისი მონაცემების უნებართვო შეგროვება;
- ყალბი შეფასებების წერა ან შეფასებების მანიპულირება;
- პლატფორმის მუშაობის დარღვევა, უსაფრთხოების მექანიზმების გვერდის ავლა, ავტომატური მასობრივი წვდომა.

დეტალური წესები — [საზოგადოების წესებში](/community-guidelines).

## 11. ანგარიშის შეზღუდვა და შეჩერება

წესების დარღვევის, რეპორტების, უსაფრთხოების საფრთხის ან კანონის მოთხოვნის შემთხვევაში შეგვიძლია: **ანგარიშის შეჩერება**, კონტენტის ან შეფასების მოხსნა/დამალვა, **ვერიფიკაციის მოხსნა** და განცხადების გაუქმება. მოქმედება დამოკიდებულია დარღვევის სიმძიმეზე. შეჩერებულ ანგარიშზე შესვლა და შეტყობინებების გაგზავნა შეუძლებელია; ჩვენ შეიძლება მოგაწოდოთ მიზეზი. თუ ფიქრობთ, რომ გადაწყვეტილება არასწორია, დაგვიკავშირდით გვერდზე [დახმარება](/support) — განვიხილავთ.

მომხმარებელს ასევე შეუძლია სხვა მომხმარებლის **დაბლოკვა** და ჩატიდან დარეპორტება.

## 12. ანგარიშის წაშლა და შეწყვეტა

- ანგარიშის წაშლა ნებისმიერ დროს შეგიძლიათ აპიდან: **პროფილი → ანგარიშის წაშლა** ([ინსტრუქცია](/delete-account)). წაშლა შეუძლებელია მიმდინარე (არჩეული, დაუსრულებელი) სამუშაოს დროს.
- წაშლისას მონაცემები იშლება ან ანონიმიზდება [კონფიდენციალურობის პოლიტიკის](/privacy) მიხედვით; დასრულებული სამუშაოები და შეფასებები ანონიმიზებული სახით შეიძლება დარჩეს.
- ჩვენც შეგვიძლია ანგარიშის შეწყვეტა ამ პირობების არსებითი დარღვევისას ან კანონით მოთხოვნისას.
- შეწყვეტის შემდეგ ძალაში რჩება ის დებულებები, რომელთა ბუნებიდან გამომდინარე ეს გულისხმობს (მაგ. პასუხისმგებლობის, დავების, ინტელექტუალური საკუთრების).

## 13. ინტელექტუალური საკუთრება

Ostato-ის სახელი, ლოგო, დიზაინი, აპლიკაცია, ტექსტები და პროგრამული კოდი ჩვენი ან ჩვენი ლიცენზიარების საკუთრებაა. გაძლევთ შეზღუდულ, არაექსკლუზიურ, არაგადაცემად უფლებას, გამოიყენოთ პლატფორმა პირადი/პროფესიული მიზნებისთვის ამ პირობების ფარგლებში. აკრძალულია კოდის კოპირება, დეკომპილაცია, მასობრივი ამოღება (scraping) ან ჩვენი სახელის/ბრენდის უნებართვო გამოყენება.

## 14. მესამე მხარეების სერვისები და ბმულები

პლატფორმა იყენებს მესამე მხარეების სერვისებს (მაგ. ავტორიზაცია, შეტყობინებები, მისამართის ძებნა — იხ. [კონფიდენციალურობა](/privacy)) და შეიძლება შეიცავდეს გარე ბმულებს. მათ კონტენტსა და პრაქტიკაზე პასუხისმგებელნი არ ვართ; მათზე მათი პირობები ვრცელდება.

## 15. პასუხისმგებლობის უარყოფა

- პლატფორმა მოწოდებულია „**როგორც არის**“ და „როგორც ხელმისაწვდომია“. ვცდილობთ უწყვეტ, უსაფრთხო მუშაობას, თუმცა ამას ვერ გარანტირებთ.
- ჩვენ არ ვამოწმებთ ყველა განცხადებას, პროფილს, შეფასებას ან შეთანხმებას და **არ ვგარანტირებთ** ოსტატების კვალიფიკაციას, სამუშაოს ხარისხს, დროულობას, უსაფრთხოებას ან დამკვეთის კეთილსინდისიერებას.
- ვერიფიკაცია ვინაობის დადასტურებაა და არა კვალიფიკაციის ან ნასამართლეობის შემოწმება.
- სამუშაოს დაწყებამდე გამოიყენეთ საკუთარი განსჯა: შეადარეთ ოსტატები, გადაამოწმეთ შეფასებები და ნამუშევრები, შეთანხმდით დეტალებზე წინასწარ.

## 16. პასუხისმგებლობის შეზღუდვა

კანონით დაშვებული ფარგლებში Ostato არ აგებს პასუხს დამკვეთსა და ოსტატს შორის დავაზე, სამუშაოს ხარისხზე, ქონებისა თუ ჯანმრთელობისთვის მიყენებულ ზიანზე, დაკარგულ შემოსავალზე ან მესამე მხარეთა ქმედებებზე. ჩვენი ერთობლივი პასუხისმგებლობა თქვენს წინაშე, რომელიც პლატფორმის გამოყენებას უკავშირდება, შეზღუდულია იმ ზიანით, რომელიც პირდაპირ გამოიწვია ჩვენმა დარღვევამ.

**ეს შეზღუდვა არ ვრცელდება** პასუხისმგებლობაზე, რომლის გამორიცხვა ან შეზღუდვა საქართველოს კანონმდებლობით დაუშვებელია (მათ შორის განზრახვით ან უხეში გაუფრთხილებლობით გამოწვეულ ზიანზე და მომხმარებელთა დაცვის იმპერატიულ ნორმებზე).

## 17. ანაზღაურება

თქვენ ეთანხმებით, აანაზღაუროთ Ostato-ისთვის ის ზიანი და ხარჯები, რაც გამოწვეულია ამ პირობების, საზოგადოების წესების ან კანონის თქვენ მიერ დარღვევით, თქვენი კონტენტით ან სხვა მომხმარებელთან თქვენი შეთანხმების/სამუშაოს დარღვევით — იმ ფარგლებში, რაც კანონით დაშვებულია.

## 18. დავების გადაწყვეტა და მოქმედი კანონმდებლობა

- დავის შემთხვევაში ჯერ დაგვიკავშირდით გვერდზე [დახმარება](/support) — ვეცდებით, საკითხი მოლაპარაკებით გადავწყვიტოთ.
- თუ დავა ასე არ გადაწყდება, ის განიხილება **საქართველოს კომპეტენტურ სასამართლოში**, საქართველოს კანონმდებლობის შესაბამისად. ეს დებულება არ ზღუდავს მომხმარებლის იმპერატიულ უფლებებს.
- ამ პირობებზე და პლატფორმის გამოყენებაზე ვრცელდება **საქართველოს კანონმდებლობა**.

## 19. აპლიკაციების მაღაზიები

თუ აპლიკაციას Apple App Store-დან ან Google Play-დან იყენებთ, ეს პირობები ჩვენსა და თქვენს შორის დგება და არა მაღაზიასთან. მაღაზია არ არის პასუხისმგებელი აპლიკაციის მხარდაჭერაზე ან თქვენს მოთხოვნებზე და არ არის ამ პირობების მხარე; თუმცა მაღაზიის წესები (მათ შორის Apple-ისა და Google-ის) ასევე გეხებათ.

## 20. ცვლილებები

პირობებს, პლატფორმას ან აპლიკაციას შეიძლება ვცვლიდეთ. არსებითი ცვლილების შემთხვევაში აპში ან ვებგვერდზე გაგაფრთხილებთ; ბოლო განახლების თარიღი მითითებულია ტექსტის დასაწყისში. ცვლილების შემდეგ პლატფორმის გამოყენების გაგრძელება ახალ პირობებზე თანხმობად ითვლება. თუ არ ეთანხმებით, შეგიძლიათ ანგარიში წაშალოთ.

## 21. შეტყობინებები და ელექტრონული თანხმობა

თანახმა ხართ, მიიღოთ ჩვენგან შეტყობინებები ელექტრონული ფორმით (აპში, push-შეტყობინებით, ელფოსტით ან ვებგვერდზე). ელექტრონული შეთანხმება და ჩანაწერები (მათ შორის ჩატში დათანხმება) აქვს იურიდიული ძალა იმ ფარგლებში, რაც კანონით დაშვებულია. პუშ-შეტყობინებების გამორთვა შეგიძლიათ აპში; მნიშვნელოვანი (მაგ. უსაფრთხოებასთან დაკავშირებული) შეტყობინებები შეიძლება მაინც გამოგიგზავნოთ.

## 22. ზოგადი დებულებები

- **მთლიანი შეთანხმება.** ეს პირობები, [კონფიდენციალურობის პოლიტიკა](/privacy) და [საზოგადოების წესები](/community-guidelines) წარმოადგენს ჩვენსა და თქვენს შორის სრულ შეთანხმებას პლატფორმის გამოყენებაზე.
- **ურთიერთობა.** ეს პირობები არ ქმნის თანამშრომლობას, წარმომადგენლობას, ერთობლივ საწარმოს ან შრომით ურთიერთობას Ostato-სა და ოსტატს/დამკვეთს შორის.
