## 12. ანგარიშის შეზღუდვა და შეჩერება

წესების დარღვევის, რეპორტების, უსაფრთხოების საფრთხის ან კანონის მოთხოვნის შემთხვევაში შეგვიძლია: **ანგარიშის შეჩერება**, კონტენტის ან შეფასების მოხსნა/დამალვა, **ვერიფიკაციის მოხსნა** და განცხადების გაუქმება. მოქმედება დამოკიდებულია დარღვევის სიმძიმეზე. შეჩერებულ ანგარიშზე შესვლა და შეტყობინებების გაგზავნა შეუძლებელია; ჩვენ შეიძლება მოგაწოდოთ მიზეზი. თუ ფიქრობთ, რომ გადაწყვეტილება არასწორია, დაგვიკავშირდით გვერდზე [დახმარება](/support) — განვიხილავთ.

მომხმარებელს ასევე შეუძლია სხვა მომხმარებლის **დაბლოკვა** და ჩატიდან დარეპორტება.

## 13. ანგარიშის წაშლა და შეწყვეტა

