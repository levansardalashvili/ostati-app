## 1. პლატფორმა

Ostati („ჩვენ“, „პლატფორმა“) არის ორმხრივი პლატფორმა (მობილური აპლიკაცია და ვებგვერდი), რომელიც საქართველოში აკავშირებს სახლის სერვისების მაძიებელ მომხმარებლებს („**დამკვეთი**“) ადგილობრივ ოსტატებთან („**ოსტატი**“). ჩვენ ვქმნით ადგილს ერთმანეთის პოვნის, ურთიერთობისა და შეთანხმებისთვის.

**Ostati არ არის** სამუშაოს შემსრულებელი, დამკვეთისა და ოსტატის დამქირავებელი ან წარმომადგენელი და არც მათ შორის შეთანხმების მხარე. სამუშაოს პირობებზე, ფასზე, ხარისხზე და შესრულებაზე პასუხისმგებელნი არიან თავად დამკვეთი და ოსტატი.

ამ პირობებთან ერთად თქვენზე ვრცელდება [კონფიდენციალურობის პოლიტიკა](/privacy) და [საზოგადოების წესები](/community-guidelines). პლატფორმის გამოყენებით ეთანხმებით მათ ერთობლიობას. თუ არ ეთანხმებით, პლატფორმას ნუ გამოიყენებთ.

## 2. ვის შეუძლია გამოყენება

- პლატფორმის გამოყენება შეუძლია მხოლოდ **18 წლის და უფროსი** პირს, რომელსაც კანონით აქვს ხელშეკრულების დადების უფლება.
- ოსტატმა უნდა იმოქმედოს კანონმდებლობის შესაბამისად: იყოს რეგისტრირებული/დასაბეგრი, სადაც ეს კანონით მოითხოვება, და ჰქონდეს სამუშაოსთვის საჭირო ლიცენზია/ნებართვა.
- პლატფორმა განკუთვნილია საქართველოში მიწოდებული სერვისებისთვის.

## 3. ანგარიში

- **ერთი ანგარიში — ერთი როლი.** ანგარიში არის ან დამკვეთის, ან ოსტატის.
- შეგიძლიათ დარეგისტრირდეთ ელფოსტით, Google-ით ან Apple-ით. მიუთითეთ **ზუსტი და მიმდინარე** ინფორმაცია და განაახლეთ ის ცვლილებისას.
- დაიცავით თქვენი შესვლის მონაცემები. ანგარიშზე შესრულებულ მოქმედებებზე თქვენ ხართ პასუხისმგებელი; უნებართვო წვდომის შემთხვევაში დაუყოვნებლივ შეგვატყობინეთ.
- ერთ პირს ერთი ანგარიში აქვს; სხვისი სახელით ან ყალბი მონაცემებით ანგარიშის შექმნა აკრძალულია.

## 4. ოსტატების ვერიფიკაცია

ოსტატს შეუძლია ვერიფიკაცია მოითხოვოს: აპში აკეთებს სელფის, ჩვენი გუნდი ადარებს მას პროფილის ფოტოს და, ფოტოები ერთი ადამიანისაა თუ არა, იღებს გადაწყვეტილებას.

- ვერიფიკაციის გარეშე ოსტატი **ფასს ვერ სთავაზობს** განცხადებას.
- „ვერიფიცირებული“ ნიშანი **მხოლოდ ვინაობის დადასტურებას** ნიშნავს. ის **არ არის** გარანტია სამუშაოს ხარისხზე, კვალიფიკაციაზე, ლიცენზიაზე ან ნასამართლეობის არარსებობაზე.
- სელფი კერძოა და არ ქვეყნდება (დეტალები — [კონფიდენციალურობის პოლიტიკაში](/privacy)).
- შეგვიძლია ვერიფიკაციაზე უარი ვთქვათ ან უკვე მინიჭებული მოვხსნათ, თუ წესები დაირღვა ან მონაცემები არასწორია.

## 5. განცხადებები და შეთავაზებები

- **განცხადება.** დამკვეთი აქვეყნებს განცხადებას (კატეგორია, აღწერა, ფოტოები, რაიონი, მისამართი, სასურველი დრო). **დამკვეთი ფასს არ უთითებს.** განცხადებების რაოდენობა და მათი მოქმედების ვადა შეზღუდულია (მიმდინარე მნიშვნელობები აპშია მითითებული და შეიძლება შეიცვალოს).
- **მისამართი.** ზუსტი მისამართი სხვა ოსტატებს არ ჩანს; ის ხელმისაწვდომია მხოლოდ არჩეული ოსტატისთვის.
- **შეთავაზება.** ვერიფიცირებული ოსტატი განცხადების დეტალების ნახვის შემდეგ სთავაზობს **კონკრეტულ ფასს**. ოსტატს შეუძლია დაინტერესება გააუქმოს, სანამ დამკვეთმა არჩევანი არ გააკეთა.
- **ჩატი.** მხარეები დეტალებს ჩატში აზუსტებენ. ფასის შეცვლა ხდება სტრუქტურირებული ბარათით: ოსტატი სთავაზობს, დამკვეთი ეთანხმება ან უარყოფს. შეთავაზებას ვადა აქვს.
- **არჩევა.** დამკვეთი ირჩევს ოსტატს; შეთანხმებული ფასი ფიქსირდება და არჩეულ ოსტატს ეცნობება. დანარჩენ დაინტერესებულ ოსტატებს ეცნობებათ, რომ განცხადება სხვას გადაეცა.
- ფასი და პირობები, რომელზეც დამკვეთი და ოსტატი შეთანხმდნენ, არის **მათ შორის** შეთანხმება; Ostati მასში მხარე არ არის.

## 6. სამუშაოს შესრულება, დასრულება და შეფასება

- ოსტატი ასრულებს სამუშაოს შეთანხმებულ დროს და აპში აფიქსირებს დასრულებას („სამუშაო დავასრულე“). დაგეგმილ დრომდე დასრულების მონიშვნა შეუძლებელია.
- დამკვეთს ეგზავნება დასრულების ბარათი. დამკვეთი **ადასტურებს დასრულებას და აფასებს ოსტატს** — შეფასება სავალდებულო ეტაპია.
- თუ დამკვეთი განსაზღვრულ ვადაში (ამჟამად 72 საათი) არ რეაგირებს, დასრულება შეიძლება ავტომატურად დადასტურდეს; შეფასების დატოვება მაინც შესაძლებელია.
- სამუშაოს დროს ორივე მხარე ვალდებულია, იმოქმედოს კეთილსინდისიერად, მშვიდად და კანონის დაცვით.

## 7. დავები

- თუ სამუშაო არ არის შესრულებული ან შესრულებულია არასათანადოდ, დამკვეთს შეუძლია დააფიქსიროს **პრობლემა** დასრულების დადასტურების ნაცვლად. განცხადება „დავაზე“ გადადის და მას ჩვენი გუნდი განიხილავს.
- განხილვისას შეგვიძლია გამოვიყენოთ მხარეთა ჩანაწერები, ჩატი და ფოტოები (იხ. [კონფიდენციალურობა](/privacy)). გადაწყვეტილებით განცხადება შეიძლება გაუქმდეს ან დასადასტურებლად დაუბრუნდეს დამკვეთს.
- ერთ განცხადებაზე დავის დაფიქსირება შეზღუდულია (ამჟამად ორჯერ).
- ჩვენი გადაწყვეტილება არ ზღუდავს მხარეთა უფლებას, ზიანის ანაზღაურება მოითხოვონ კანონით დადგენილი წესით.
- დავის მიღმა, დამატებით შეგიძლიათ მომხმარებელი ან სამუშაო დაარეპორტოთ (მაგ. გამოუცხადებლობა, უხამსი ქცევა).

## 8. გაუქმება და განცხადების ვადა

- **დამკვეთს** შეუძლია განცხადების გაუქმება მოლოდინის ეტაპზე; ოსტატის არჩევის შემდეგ — მიზეზის მითითებით.
- **ოსტატს** შეუძლია არჩეული სამუშაოს გაუქმება მიზეზის მითითებით. ასეთ შემთხვევაში დამკვეთს შეუძლია განცხადება ხელახლა გახსნას დანარჩენი ოსტატებისთვის; გაუქმებული ოსტატი განცხადებას აღარ ხედავს.
- მოლოდინის ეტაპზე მყოფი განცხადება განსაზღვრული ვადის (ამჟამად 30 დღე) გასვლისას ავტომატურად უქმდება; ვადის ამოწურვამდე შეგახსენებთ და შეგიძლიათ განცხადება განაახლოთ.
- სისტემატური, უსაფუძვლო გაუქმებები ან გამოუცხადებლობა შეიძლება გახდეს ანგარიშის შეზღუდვის საფუძველი.

## 9. ფასი და ანგარიშსწორება

- აპში ნაჩვენები ფასი არის დამკვეთისა და ოსტატის **შეთანხმება**.
- **Ostati ამჟამად არ ამუშავებს გადახდებს** და არ იღებს კომისიას: ანგარიშსწორება ხდება პლატფორმის გარეთ, მხარეებს შორის. რეგისტრაცია და განცხადებებში მონაწილეობა ამჟამად უფასოა.
- არასდროს გადასცეთ საბანკო ბარათის მონაცემები ან ერთჯერადი კოდები მესამე პირს; ჩვენი გუნდი მათ არასდროს გთხოვთ.
- თუ მომავალში დავამატებთ აპლიკაციაში გადახდას ან საკომისიოს, ამ პირობებს ან ცალკე დამატებით პირობებს წინასწარ გაცნობებთ, და ახალი პირობები მხოლოდ მას შემდეგ იმოქმედებს.
- გადასახადები და სხვა სავალდებულო გადასახდელები თქვენ ეკისრებათ, კანონმდებლობის შესაბამისად.

## 10. შეფასებები და თქვენი კონტენტი

- **შეფასებები** ჩანს **ანონიმურად**: ავტორი არც საჯაროდ ჩანს და არც ოსტატისთვის. შეფასების დატოვება შეუძლია მხოლოდ დამკვეთს, სამუშაოს დასრულების შემდეგ; ოსტატს შეუძლია ერთხელ უპასუხოს.
- გვაქვს უფლება, დავმალოთ ან მოვხსნათ შეფასება/პასუხი, რომელიც არღვევს წესებს (შეურაცხმყოფელი, ყალბი, შეუსაბამო, პირად მონაცემებს შეიცავს).
- **თქვენი კონტენტი** (ტექსტი, ფოტოები, პროფილი, შეფასებები) რჩება თქვენი. თქვენ გვანიჭებთ არაექსკლუზიურ, უფლებას, გამოვიყენოთ ის პლატფორმის მუშაობისთვის (მაგ. მეორე მხარისთვის ჩვენება, შეთანხმების დამადასტურებელი ჩანაწერი, უსაფრთხოება).
- გარანტიას იძლევით, რომ გაქვთ კონტენტის ატვირთვის უფლება და ის არ არღვევს სხვისი უფლებებს ან კანონს.
- გამოხმაურება და შეთავაზებები პლატფორმის გაუმჯობესებაზე შეგვიძლია გამოვიყენოთ ანაზღაურების გარეშე.

