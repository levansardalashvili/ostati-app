- შეწყვეტის შემდეგ ძალაში რჩება ის დებულებები, რომელთა ბუნებიდან გამომდინარე ეს გულისხმობს (მაგ. პასუხისმგებლობის, დავების, ინტელექტუალური საკუთრების).

## 14. ინტელექტუალური საკუთრება

Ostati-ის სახელი, ლოგო, დიზაინი, აპლიკაცია, ტექსტები და პროგრამული კოდი ჩვენი ან ჩვენი ლიცენზიარების საკუთრებაა. გაძლევთ შეზღუდულ, არაექსკლუზიურ, არაგადაცემად უფლებას, გამოიყენოთ პლატფორმა პირადი/პროფესიული მიზნებისთვის ამ პირობების ფარგლებში. აკრძალულია კოდის კოპირება, დეკომპილაცია, მასობრივი ამოღება (scraping) ან ჩვენი სახელის/ბრენდის უნებართვო გამოყენება.

## 15. მესამე მხარეების სერვისები და ბმულები

პლატფორმა იყენებს მესამე მხარეების სერვისებს (მაგ. ავტორიზაცია, შეტყობინებები, მისამართის ძებნა — იხ. [კონფიდენციალურობა](/privacy)) და შეიძლება შეიცავდეს გარე ბმულებს. მათ კონტენტსა და პრაქტიკაზე პასუხისმგებელნი არ ვართ; მათზე მათი პირობები ვრცელდება.

## 16. პასუხისმგებლობის უარყოფა

- პლატფორმა მოწოდებულია „**როგორც არის**“ და „როგორც ხელმისაწვდომია“. ვცდილობთ უწყვეტ, უსაფრთხო მუშაობას, თუმცა ამას ვერ გარანტირებთ.
- ჩვენ არ ვამოწმებთ ყველა განცხადებას, პროფილს, შეფასებას ან შეთანხმებას და **არ ვგარანტირებთ** ოსტატების კვალიფიკაციას, სამუშაოს ხარისხს, დროულობას, უსაფრთხოებას ან დამკვეთის კეთილსინდისიერებას.
- ვერიფიკაცია ვინაობის დადასტურებაა და არა კვალიფიკაციის ან ნასამართლეობის შემოწმება.
- სამუშაოს დაწყებამდე გამოიყენეთ საკუთარი განსჯა: შეადარეთ ოსტატები, გადაამოწმეთ შეფასებები და ნამუშევრები, შეთანხმდით დეტალებზე წინასწარ.

## 17. პასუხისმგებლობის შეზღუდვა

კანონით დაშვებული ფარგლებში Ostati არ აგებს პასუხს დამკვეთსა და ოსტატს შორის დავაზე, სამუშაოს ხარისხზე, ქონებისა თუ ჯანმრთელობისთვის მიყენებულ ზიანზე, დაკარგულ შემოსავალზე ან მესამე მხარეთა ქმედებებზე. ჩვენი ერთობლივი პასუხისმგებლობა თქვენს წინაშე, რომელიც პლატფორმის გამოყენებას უკავშირდება, შეზღუდულია იმ ზიანით, რომელიც პირდაპირ გამოიწვია ჩვენმა დარღვევამ.

**ეს შეზღუდვა არ ვრცელდება** პასუხისმგებლობაზე, რომლის გამორიცხვა ან შეზღუდვა საქართველოს კანონმდებლობით დაუშვებელია (მათ შორის განზრახვით ან უხეში გაუფრთხილებლობით გამოწვეულ ზიანზე და მომხმარებელთა დაცვის იმპერატიულ ნორმებზე).

## 18. ანაზღაურება

თქვენ ეთანხმებით, აანაზღაუროთ Ostati-ისთვის ის ზიანი და ხარჯები, რაც გამოწვეულია ამ პირობების, საზოგადოების წესების ან კანონის თქვენ მიერ დარღვევით, თქვენი კონტენტით ან სხვა მომხმარებელთან თქვენი შეთანხმების/სამუშაოს დარღვევით — იმ ფარგლებში, რაც კანონით დაშვებულია.

