- წაშლისას მონაცემები იშლება ან ანონიმიზდება [კონფიდენციალურობის პოლიტიკის](/privacy) მიხედვით; დასრულებული სამუშაოები და შეფასებები ანონიმიზებული სახით შეიძლება დარჩეს.
