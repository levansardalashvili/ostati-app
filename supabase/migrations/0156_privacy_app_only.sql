## 4. რისთვის ვიყენებთ

- ანგარიშის, განცხადებების, ჩატის, ფასის შეთანხმებისა და შეფასებების მუშაობისთვის;
- ოსტატის ვერიფიკაციისთვის (ვერიფიცირებული ოსტატები სიაში პირველები ჩანან);
- push-შეტყობინებებისთვის — თითოეული ტიპის გამორთვა შეგიძლიათ აპში;
- თაღლითობისა და წესების დარღვევის პრევენციისთვის, რეპორტებისა და დავების განსახილველად;
- აპის შეცდომების გასასწორებლად.

## 5. ნებართვები თქვენს მოწყობილობაზე

აპი ნებართვას ითხოვს მხოლოდ მაშინ, როცა შესაბამისი ფუნქცია გჭირდებათ:

- **კამერა** — ფოტოს ან სელფის გადასაღებად;
- **ფოტოგალერეა** — ფოტოს ასარჩევად;
- **ადგილმდებარეობა** — მხოლოდ როცა დააჭერთ „ჩემი მდებარეობის გამოყენება“-ს: კოორდინატი ერთხელ ისაზღვრება მისამართის ავტომატურად შესავსებად და არ ინახება;
- **შეტყობინებები** — push-შეტყობინებების მისაღებად.

უარის შემთხვევაში აპი იმუშავებს, უბრალოდ შესაბამისი ფუნქცია მიუწვდომელი იქნება. ნებართვას მოწყობილობის პარამეტრებში შეცვლით.

## 6. ვისთან ვიზიარებთ

- **მეორე მხარესთან** — იმ ოდენობით, რაც სამუშაოსთვის სჭირდება (იხ. [3. თავი](#s3)).
- **სერვისებთან, რომლებზეც აპი მუშაობს:**
  - **Supabase** — მონაცემთა ბაზა, ავტორიზაცია, ფაილების საცავი;
  - **Expo** — push-შეტყობინებების გადაცემა;
  - **Google და Apple** — შესვლა ამ ანგარიშებით;
  - **OpenStreetMap Nominatim** — მისამართის ძებნა (იგზავნება აკრეფილი ტექსტი ან, „ჩემი მდებარეობის“ დაჭერისას, კოორდინატი);
  - **Resend** — დასადასტურებელი კოდის გაგზავნა ელფოსტაზე;
  - **Vercel** — ამ ვებგვერდის ჰოსტინგი.
- **უფლებამოსილ ორგანოებთან**, თუ ამას კანონი მოითხოვს.

მონაცემებს **არ ვყიდით**. ზოგიერთი ეს სერვისი მონაცემებს საქართველოს გარეთ ამუშავებს. ვებგვერდი თვალთვალის ან სარეკლამო ქუქიებს არ იყენებს.

## 7. რამდენ ხანს ვინახავთ

- მონაცემებს ვინახავთ, სანამ ანგარიში არსებობს.
- **ანგარიშის წაშლისას** იშლება პროფილი, ფოტოები, ჩატები, სელფი და აქტიური განცხადებები.
- **დასრულებული სამუშაოები და მათი შეფასებები** რჩება ანონიმიზებული სახით (თქვენი სახელის, მისამართისა და ფოტოების გარეშე), რომ ოსტატის რეიტინგი არ დაზიანდეს.
- **რეპორტებს** ვინახავთ უსაფრთხოების მიზნით.
- დაუსრულებელი განცხადების მონახაზები ავტომატურად იშლება.

