## 1. ვინ ვართ

Ostato არის აპლიკაცია, რომელიც საქართველოში აკავშირებს დამკვეთებს ადგილობრივ ოსტატებთან. ეს პოლიტიკა განმარტავს, რა მონაცემებს ამუშავებს Ostato-ის აპი (Android და iOS) და ეს ვებგვერდი. აპი განკუთვნილია 18 წლის და უფროსი მომხმარებლებისთვის.

## 2. რა მონაცემებს ვაგროვებთ

### თქვენ მიერ მოწოდებული

- **ანგარიში:** სახელი, გვარი, ელფოსტა (ან ტელეფონის ნომერი), პაროლი — ინახება მხოლოდ დაშიფრული სახით.
- **დამკვეთის მისამართი:** მისამართი, შესასვლელი, ბინა და კარის კოდი — განცხადების მისამართის წინასწარ შესავსებად.
- **განცხადება:** კატეგორია, აღწერა, ფოტოები, რაიონი, ზუსტი მისამართი, სასურველი თარიღი და დრო.
- **ოსტატის პროფილი:** პროფილის ფოტო, სპეციალობები, სამუშაო არეალი, გამოცდილება, აღწერა, სერთიფიკატებისა და ნამუშევრების ფოტოები, ფასები.
- **ვერიფიკაციის სელფი:** ოსტატის ვინაობის დასადასტურებლად. ინახება კერძო საცავში, **არასდროს ქვეყნდება** და პროფილის ფოტოდ არ იქცევა.
- **ჩატი:** შეტყობინებები, ფოტოები და ფასის შეთავაზებები.
- **შეფასებები:** ვარსკვლავები, ტექსტი და ფოტოები, ასევე ოსტატის პასუხი.
- **რეპორტები და დაბლოკვა:** რეპორტის მიზეზი და დეტალები; ვინ დაბლოკეთ.
- **მიმართვები:** დახმარების ფორმით გამოგზავნილი ელფოსტა ან ტელეფონი და ტექსტი.

### ავტომატურად შექმნილი

- მოწყობილობის **push-იდენტიფიკატორი** და პლატფორმა — შეტყობინებების გასაგზავნად (სისტემიდან გასვლისას გამოირთვება).
- შეტყობინებების პარამეტრები.
- სამუშაოს სტატუსები, ოსტატის ხელმისაწვდომობა, რეიტინგი და დასრულებული სამუშაოების რაოდენობა.
- **აპის შეცდომები:** აპის ავარიისას — შეცდომის ტექსტი, აპის ვერსია და პლატფორმა (გამოიყენება მხოლოდ შეცდომების გასასწორებლად).

### Google-ით ან Apple-ით შესვლისას

ვიღებთ სახელს და ელფოსტას, რომლებსაც ეს სერვისები გვაწვდიან.

**რასაც არ ვაგროვებთ:** ადგილმდებარეობის ისტორიას (იხ. [5. თავი](#s5)), კონტაქტების სიას, სარეკლამო იდენტიფიკატორებს.

