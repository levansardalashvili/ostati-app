## 1. ვინ ვართ და რას მოიცავს ეს პოლიტიკა

Ostati („ჩვენ“) არის პლატფორმა, რომელიც საქართველოში აკავშირებს მომხმარებლებს (დამკვეთებს) ადგილობრივ ოსტატებთან. ეს პოლიტიკა განმარტავს, როგორ ვამუშავებთ თქვენს პერსონალურ მონაცემებს, როცა იყენებთ:

- Ostati-ის მობილურ აპლიკაციას (Android და iOS);
- ამ ვებგვერდს.

მონაცემთა დამმუშავებელი ამ პოლიტიკის მიზნებისთვის არის Ostati. კითხვების შემთხვევაში იხილეთ [12. თავი](#s12).

## 2. რა მონაცემებს ვაგროვებთ

### თქვენ მიერ მოწოდებული მონაცემები

- **ანგარიში:** სახელი, გვარი, ელფოსტა (ან, როცა ეს ვარიანტი ხელმისაწვდომია, ტელეფონის ნომერი), პაროლი — ის ინახება მხოლოდ დაშიფრული სახით.
- **დამკვეთის განცხადება:** კატეგორია, აღწერა, ფოტოები, რაიონი, ზუსტი მისამართი, სასურველი თარიღი და დრო.
- **ოსტატის პროფილი:** პროფილის ფოტო, სპეციალობები, სამუშაო არეალი, გამოცდილება, აღწერა, სერთიფიკატებისა და ნამუშევრების ფოტოები, ფასები.
- **ვერიფიკაციის სელფი:** ოსტატის ვინაობის დასადასტურებლად. ის ინახება კერძო საცავში და **არასდროს ქვეყნდება**, არც პროფილის ფოტოდ იქცევა.
- **კომუნიკაცია:** ჩატის შეტყობინებები, ფოტოები და ფასის შეთავაზებები.
- **შეფასებები:** ვარსკვლავები, ტექსტი და ფოტოები, რომლებსაც სამუშაოს დასრულების შემდეგ ტოვებთ (ოსტატის პასუხიც).
- **რეპორტები და დაბლოკვა:** თუ ვინმეს ან რამეს დაარეპორტებთ, ვინახავთ რეპორტს, მიზეზს და თქვენ მიერ დამატებულ დეტალებს; ასევე ვინახავთ, ვინ დაბლოკეთ.

### ავტომატურად შექმნილი მონაცემები

- მოწყობილობის **push-იდენტიფიკატორი** (token) და პლატფორმა (Android/iOS) — შეტყობინებების გასაგზავნად. სისტემიდან გასვლისას ის გამოირთვება.
- თქვენი შეტყობინებების პარამეტრები.
- სამუშაოს სტატუსები, ოსტატის ხელმისაწვდომობა, რეიტინგი და დასრულებული სამუშაოების რაოდენობა.

### მესამე მხარეებიდან მიღებული მონაცემები

Google-ით ან Apple-ით შესვლისას ვიღებთ იმ მონაცემებს, რომლებსაც ეს სერვისები გვაწვდიან (სახელი, ელფოსტა).

**რასაც არ ვაგროვებთ:** ზუსტ GPS-ადგილმდებარეობას (მისამართს თავად წერთ), საბანკო ბარათის მონაცემებს (გადახდა აპში არ ხდება), კონტაქტების სიას, სარეკლამო იდენტიფიკატორებს.

