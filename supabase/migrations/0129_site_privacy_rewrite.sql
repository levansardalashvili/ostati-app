## 5. ნებართვები თქვენს მოწყობილობაზე

აპი ითხოვს ნებართვას მხოლოდ მაშინ, როცა შესაბამისი ფუნქცია გჭირდებათ:

- **კამერა** — ფოტოს/სელფის გადასაღებად;
- **ფოტოგალერეა** — ფოტოს ასარჩევად;
- **შეტყობინებები** — push-შეტყობინებების მისაღებად.

ნებართვის უარყოფის შემთხვევაში აპი კვლავ იმუშავებს, უბრალოდ შესაბამისი ფუნქცია მიუწვდომელი იქნება. ნებართვის შეცვლა შეგიძლიათ მოწყობილობის პარამეტრებში.

## 6. ვისთან ვიზიარებთ მონაცემებს

- **მეორე მხარესთან** — იმ ოდენობით, რაც სამუშაოსთვის სჭირდება (იხ. [3. თავი](#s3)).
- **მომსახურების მიმწოდებლებთან**, რომლებიც ჩვენი სახელით ამუშავებენ მონაცემებს:
  - **Supabase** — მონაცემთა ბაზა, ავტორიზაცია, ფაილების საცავი;
  - **Expo** — push-შეტყობინებების გადაცემა;
  - **Google და Apple** — შესვლა ამ ანგარიშებით;
  - **OpenStreetMap Nominatim** — მისამართის ძებნა (იქ იგზავნება მხოლოდ თქვენ მიერ აკრეფილი მისამართის ტექსტი);
  - **Vercel** — ვებგვერდის ჰოსტინგი.
- **უფლებამოსილ ორგანოებთან**, თუ ამას კანონი მოითხოვს.

მონაცემებს **არ ვყიდით** და სარეკლამო მიზნით მესამე მხარეებს არ ვუზიარებთ. ზოგიერთი მომსახურების მიმწოდებელი მონაცემებს საქართველოს გარეთ ამუშავებს; ასეთ შემთხვევაში ვეყრდნობით მათ ხელშეკრულებით ნაკისრ დაცვის ვალდებულებებს.

## 7. ვებგვერდი და ქუქიები

საჯარო ვებგვერდი **არ იყენებს** სააღრიცხვო, სარეკლამო ან თვალთვალის ქუქიებს და არ მოითხოვს რეგისტრაციას. ჰოსტინგის სერვისი (Vercel) ინახავს სტანდარტულ ტექნიკურ ჟურნალებს (მაგ. IP-მისამართი, ვიზიტის დრო, გვერდი) უსაფრთხოებისა და გამართული მუშაობისთვის. ჩვენთან დაკავშირებისას მოწოდებულ ინფორმაციას ვინახავთ თქვენი მოთხოვნის დასამუშავებლად.

ადმინისტრაციული პანელი განკუთვნილია მხოლოდ Ostati-ის გუნდისთვის და სესიისთვის ტექნიკურ ქუქის იყენებს.

## 8. რამდენ ხანს ვინახავთ

- მონაცემებს ვინახავთ, სანამ თქვენი ანგარიში არსებობს.
- **ანგარიშის წაშლისას** იშლება თქვენი პროფილი, ფოტოები, ჩატები, სელფი და აქტიური განცხადებები.
- **დასრულებული სამუშაოები და მათზე დაწერილი შეფასებები** ანონიმიზებული სახით რჩება, რათა ოსტატის რეიტინგი და ისტორია არ დაზიანდეს — მათში თქვენი სახელი, მისამართი და ფოტოები აღარ არის.
- **რეპორტებს** ვინახავთ უსაფრთხოების მიზნით.
- ვერიფიკაციის სელფი ინახება ანგარიშის წაშლამდე.
- გამოუქვეყნებელი განცხადების მონახაზები ავტომატურად იშლება, თუ ისინი დიდხანს დაუსრულებელი რჩება.

## 9. თქვენი უფლებები

გაქვთ უფლება:

- იცოდეთ, რა მონაცემებს ვამუშავებთ და მიიღოთ მათი ასლი;
- შეასწოროთ არასწორი ან არასრული მონაცემები — პროფილის მონაცემებს თავად ცვლით აპში;
- მოითხოვოთ მონაცემების წაშლა — ანგარიშის წაშლა შეგიძლიათ აპიდან: **პროფილი → ანგარიშის წაშლა** ([დეტალები](/delete-account));
- მოითხოვოთ დამუშავების შეზღუდვა ან გააპროტესტოთ დამუშავება იქ, სადაც ის კანონიერ ინტერესს ეფუძნება;
- გამოიხმოთ თანხმობა (მაგ. გამორთოთ push-შეტყობინებები) — ეს უკვე შესრულებულ დამუშავებას არ აბათილებს;
- გაასაჩივროთ თქვენი უფლებების დარღვევა **პერსონალურ მონაცემთა დაცვის სამსახურში**.

მოთხოვნისთვის დაგვიკავშირდით [დახმარების გვერდის](/support) მეშვეობით. გიპასუხებთ გონივრულ ვადაში, კანონით დადგენილი ვადების დაცვით.

## 10. მონაცემთა უსაფრთხოება

- კავშირი დაშიფრულია, პაროლები ინახება მხოლოდ დაშიფრული სახით.
- წვდომა შეზღუდულია მონაცემთა ბაზის დონეზე — თითოეული მომხმარებელი ხედავს მხოლოდ იმას, რაც მას ეკუთვნის.
- მგრძნობიარე ფაილები (ჩატის და განცხადების ფოტოები, ვერიფიკაციის სელფი) ინახება **კერძო საცავში** და ნაჩვენებია დროებითი ბმულებით.
- ადმინისტრაციის ყველა მოქმედება (მათ შორის დარეპორტებული ჩატის ნახვა) აღირიცხება.

სრული უსაფრთხოება ინტერნეტში ვერავის შეუძლია, თუმცა რისკის მინიმუმამდე დაყვანას ვცდილობთ. უსაფრთხოების მექანიზმების შესახებ იხილეთ გვერდი [უსაფრთხოება და ნდობა](/safety).

## 11. ბავშვები

Ostati განკუთვნილია 18 წლის და უფროსი მომხმარებლებისთვის. არასრულწლოვნებისგან შეგნებულად მონაცემებს არ ვაგროვებთ; თუ ასეთ შემთხვევას აღმოვაჩენთ, შეიძლება ანგარიში და მონაცემები წავშალოთ.

